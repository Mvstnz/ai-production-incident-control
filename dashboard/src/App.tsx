function Login({ onLogin }: { onLogin: (session: Session) => void }) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<Error | null>(null);
  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const form = new FormData(event.currentTarget);
    setBusy(true);
    setError(null);
    try {
      const session = await api<Session>("/api/auth/login", {
        username: form.get("username"),
        password: form.get("password"),
      });
      setCsrf(session.csrf_token);
      onLogin(session);
    } catch (err) {
      setError(err as Error);
    } finally {
      setBusy(false);
    }
  }
  return (
    <div className="login-layout">
      <aside className="login-story">
        <Brand />
        <div>
          <span className="eyebrow">AI PRODUCTION INCIDENT CONTROL</span>
          <h1>
            Clarity when
            <br />
            operations change.
          </h1>
          <p>
            From an unstructured incident to a verified impact assessment, a
            human-approved response and an auditable action trail.
          </p>
          <div className="login-principles">
            <span>
              <CheckCheck size={18} /> Verified operational facts
            </span>
            <span>
              <ClipboardCheck size={18} /> Human-approved response
            </span>
            <span>
              <Activity size={18} /> Persisted execution evidence
            </span>
          </div>
        </div>
        <small>Synthetic manufacturing data · Local sandbox</small>
      </aside>
      <main className="login-main">
        <div className="login-form">
          <span className="eyebrow">OPERATIONS WORKSPACE</span>
          <h2>Sign in to incident control</h2>
          <p>Use a demo account generated by the project bootstrap.</p>
          <form onSubmit={submit}>
            {error && <ErrorBox error={error} />}
            <label>
              Username
              <input
                name="username"
                autoComplete="username"
                required
                autoFocus
                maxLength={100}
                placeholder="Your demo username"
              />
            </label>
            <label>
              Password
              <input
                name="password"
                type="password"
                autoComplete="current-password"
                required
                maxLength={500}
                placeholder="Your generated password"
              />
            </label>
            <button className="button primary full" disabled={busy}>
              {busy ? "Signing in…" : "Open workspace"}
              <ArrowRight size={17} />
            </button>
          </form>
          <div className="login-note">
            <ShieldCheck size={20} />
            <p>
              Access follows your assigned role. Simulated AI and synthetic ERP
              data are clearly identified in the workspace.
            </p>
          </div>
          <small>
            Generated credentials are stored locally in{" "}
            <code>.local/credentials.json</code>. They are never bundled into
            this application.
          </small>
        </div>
      </main>
    </div>
  );
}

